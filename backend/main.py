@app.post("/api/instances/{instance_id}/action")
def instance_lifecycle_action(instance_id: str, action: str):
    """Controls instance lifecycle: start, stop, restart, terminate."""
    if instance_id not in cluster_instances and action != "create":
        raise HTTPException(status_code=404, detail=f"Instance {instance_id} not found.")

    if action == "stop":
        cluster_instances[instance_id].status = "STOPPING"
    elif action == "start":
        cluster_instances[instance_id].status = "STARTING"
    elif action == "restart":
        cluster_instances[instance_id].status = "STARTING"
        cluster_instances[instance_id].requests_served = 0
    elif action == "terminate":
        del cluster_instances[instance_id]
        return {"status": "terminated", "id": instance_id}

    return cluster_instances.get(instance_id)

@app.post("/api/simulate/failure")
def inject_anomaly(anomaly_type: str):
    """Inject an explicitly simulated anomaly into the in-memory API simulator."""
    global simulated_traffic_multiplier
    if anomaly_type == "KILL_RANDOM_INSTANCE":
        running_keys = [k for k, v in cluster_instances.items() if v.status == "RUNNING"]
        if not running_keys:
            return {"status": "not_applied", "message": "No running simulated instances are available."}
        victim = random.choice(running_keys)
        cluster_instances[victim].status = "TERMINATED"
        cluster_instances[victim].healthy = False
        return {
            "status": "injected",
            "action": f"Terminated simulated instance {victim}",
            "note": "This affects in-memory demo state only; no real cloud resource is modified."
        }
    if anomaly_type == "SPIKE_TRAFFIC_300":
        simulated_traffic_multiplier = 3.0
        return {
            "status": "injected",
            "action": "Simulated telemetry traffic multiplier set to 3x.",
            "note": "This changes demo telemetry only; provide the updated observed history to /api/predict for a forecast."
        }
    if anomaly_type == "DROP_TRAFFIC_75":
        simulated_traffic_multiplier = 0.25
        return {
            "status": "injected",
            "action": "Simulated telemetry traffic multiplier set to 0.25x.",
            "note": "This changes demo telemetry only."
        }
    if anomaly_type == "CLEAR_TRAFFIC_ANOMALY":
        simulated_traffic_multiplier = 1.0
        return {"status": "cleared", "action": "Simulated telemetry multiplier reset to 1x."}
    raise HTTPException(status_code=400, detail="Unsupported anomaly type.")

class CostCompareRequest(BaseModel):
    workload_rps: List[float] = Field(..., min_length=15, max_length=10000)
    interval_minutes: int = Field(default=5, ge=1, le=60)
    fixed_instances: int = Field(default=6, ge=1, le=50)
    start_hour: int = Field(default=0, ge=0, le=23)
    start_day: int = Field(default=6, ge=0, le=6)


@app.post("/api/cost/compare")
def compare_costs(req: CostCompareRequest):
    """Simulate three autoscaling strategies on request-supplied RPS values; never returns canned benchmark numbers."""
    if req.interval_minutes != 5:
        raise HTTPException(
            status_code=422,
            detail="The bundled Python forecasting model is trained on a five-minute sample interval. Use interval_minutes=5."
        )
    if any(value < 0 for value in req.workload_rps):
        raise HTTPException(status_code=422, detail="RPS values must be non-negative.")
    if not MODEL_ARTIFACT_PATH.is_file():
        raise HTTPException(status_code=409, detail="Train the model with POST /api/train before comparing predictive scaling.")

    predictor = WorkloadPredictor(str(MODEL_ARTIFACT_PATH))
    values = [float(value) for value in req.workload_rps]
    count = len(values)
    interval_hours = req.interval_minutes / 60.0
    rate = current_policy["cost_per_instance_hour"]
    capacity = current_policy["instance_capacity_rps"]
    target_capacity = capacity * current_policy["target_cpu"] / 100.0
    min_instances = current_policy["min_instances"]
    max_instances = current_policy["max_instances"]
    cooldown_steps = max(1, math.ceil(current_policy["cooldown_seconds"] / (req.interval_minutes * 60)))

    fixed_count = max(min_instances, min(max_instances, req.fixed_instances))
    fixed_counts = [fixed_count] * count

    reactive_counts = []
    reactive_instances = 4
    last_reactive_scale = -10**9
    for idx, rps in enumerate(values):
        cpu_before = min(100.0, rps / max(1.0, reactive_instances * capacity) * 100.0)
        if idx - last_reactive_scale >= cooldown_steps:
            if cpu_before > current_policy["scale_up_cpu"] and reactive_instances < max_instances:
                reactive_instances += 1
                last_reactive_scale = idx
            elif cpu_before < current_policy["scale_down_cpu"] and reactive_instances > min_instances:
                reactive_instances -= 1
                last_reactive_scale = idx
        reactive_counts.append(reactive_instances)

    predictive_counts = []
    predictive_instances = 4
    last_predictive_scale = -10**9
    for idx, rps in enumerate(values):
        if idx >= 14:
            minute_of_day = req.start_hour * 60 + idx * req.interval_minutes
            hour = (minute_of_day // 60) % 24
            day = (req.start_day + minute_of_day // (24 * 60)) % 7
            forecast = predictor.predict_next(values[:idx + 1], current_hour=hour, current_day=day)
            peak_forecast = max(
                forecast["predicted_workload_5m"],
                forecast["predicted_workload_10m"],
                forecast["predicted_workload_15m"],
            )
        else:
            # Until enough history exists, size to the current observed load, not fabricated predictions.
            peak_forecast = rps

        required = max(min_instances, min(max_instances, math.ceil(peak_forecast / max(1.0, target_capacity))))
        cpu_now = min(100.0, rps / max(1.0, predictive_instances * capacity) * 100.0)
        if idx - last_predictive_scale >= cooldown_steps:
            updated = predictive_instances
            if required > predictive_instances:
                updated = required
            elif required < predictive_instances and cpu_now < current_policy["scale_down_cpu"]:
                updated = max(min_instances, predictive_instances - 1)
            if updated != predictive_instances:
                predictive_instances = updated
                last_predictive_scale = idx
        predictive_counts.append(predictive_instances)

    def summarize(instances_by_step: List[int]) -> Dict[str, Any]:
        cpu_values = [
            min(100.0, rps / max(1.0, instances * capacity) * 100.0)
            for rps, instances in zip(values, instances_by_step)
        ]
        scale_actions = sum(
            1 for previous, current in zip(instances_by_step, instances_by_step[1:])
            if previous != current
        )
        return {
            "total_cost_usd": round(sum(instances_by_step) * rate * interval_hours, 2),
            "instance_hours": round(sum(instances_by_step) * interval_hours, 2),
            "avg_cpu_percent": round(sum(cpu_values) / count, 1),
            "sla_violations_estimate": sum(cpu > 90.0 for cpu in cpu_values),
            "scale_actions": scale_actions,
            "instance_count_by_step": instances_by_step,
        }

    fixed = summarize(fixed_counts)
    reactive = summarize(reactive_counts)
    predictive = summarize(predictive_counts)
    savings = round(fixed["total_cost_usd"] - predictive["total_cost_usd"], 2)
    saving_percent = round(savings / fixed["total_cost_usd"] * 100.0, 1) if fixed["total_cost_usd"] else 0.0

    return {
        "simulation_only": True,
        "workload_points": count,
        "interval_minutes": req.interval_minutes,
        "currency": "USD",
        "data_source": "RPS values supplied in this request; not live cloud billing telemetry",
        "strategies": {"fixed": fixed, "reactive": reactive, "predictive": predictive},
        "predictive_savings_vs_fixed_usd": savings,
        "predictive_savings_vs_fixed_percent": saving_percent,
        "note": "SLA violations are simplified estimates where simulated CPU exceeds 90%; they are not production SLA measurements."
    }

