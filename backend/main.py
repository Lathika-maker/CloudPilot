@app.get("/api/telemetry/stream")
def get_telemetry():
    """Returns current cluster telemetry, workload metrics, and running instances."""
    running_vms = [v for v in cluster_instances.values() if v.status == "RUNNING"]
    avg_cpu = sum(v.cpu_usage for v in running_vms) / max(1, len(running_vms))
    avg_mem = sum(v.memory_usage for v in running_vms) / max(1, len(running_vms))
    total_rps = int((sum(v.requests_served for v in running_vms) % 2000 + 400) * simulated_traffic_multiplier)

    return {
        "timestamp": datetime.datetime.utcnow().isoformat(),
        "requests_per_second": total_rps,
        "active_users": total_rps * 4,
        "cluster_cpu": round(avg_cpu, 1),
        "cluster_memory": round(avg_mem, 1),
        "active_instances": len(running_vms),
        "total_instances": len(cluster_instances),
        "estimated_hourly_cost": round(len(running_vms) * current_policy["cost_per_instance_hour"], 2)
    }

@app.post("/api/dataset/upload")
async def upload_dataset(file: UploadFile = File(...)):
    """Validate CSV or JSON workload records and return a small preview (does not persist the upload)."""
    content = await file.read()
    try:
        decoded = content.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise HTTPException(status_code=400, detail="Upload must be UTF-8 text.") from exc
    filename = (file.filename or "").lower()

    if filename.endswith(".json") or "json" in (file.content_type or "").lower():
        try:
            payload = json.loads(decoded)
        except json.JSONDecodeError as exc:
            raise HTTPException(status_code=400, detail="Invalid JSON file.") from exc
        records = payload.get("data", payload.get("records", [])) if isinstance(payload, dict) else payload
        if not isinstance(records, list) or not records or not all(isinstance(row, dict) for row in records):
            raise HTTPException(status_code=400, detail="JSON must be a non-empty array of objects or an object with a data/records array.")
        headers = list(records[0].keys())
        row_count = len(records)
        preview = records[:5]
    else:
        reader = csv.DictReader(io.StringIO(decoded))
        headers = reader.fieldnames or []
        records = list(reader)
        if not headers or not records:
            raise HTTPException(status_code=400, detail="CSV must include a header and at least one data row.")
        row_count = len(records)
        preview = records[:5]

    if not headers:
        raise HTTPException(status_code=400, detail="No columns could be detected.")
    return {
        "filename": file.filename or "uploaded-dataset",
        "detected_columns": headers,
        "total_rows": row_count,
        "preview": preview,
        "status": "validated_preview_only",
        "persisted": False,
        "message": "File structure validated. This endpoint returns a preview only; upload data is not stored or passed to model training."
    }

class SyntheticWorkloadRequest(BaseModel):
    starting_users: int = 1000
    growth_rate: float = 15.0
    peak_users: int = 8000
    spike_probability: float = 0.1
    duration_minutes: int = 120
    interval_minutes: int = 5

@app.post("/api/workload/generate")
def generate_synthetic_workload(req: SyntheticWorkloadRequest):
    """Generates synthetic time-series workload with customizable spikes and diurnal cycles."""
    points = []
    base_time = datetime.datetime.utcnow()
    current_users = float(req.starting_users)
    steps = int(req.duration_minutes / req.interval_minutes)

    for i in range(steps):
        t = base_time + datetime.timedelta(minutes=i * req.interval_minutes)
        diurnal = math.sin((i / steps) * math.pi)
        spike = random.uniform(1.8, 3.0) if random.random() < req.spike_probability else 1.0
        current_users = min(req.peak_users, (current_users * (1 + req.growth_rate / 100) * diurnal + 500) * spike)
        rps = int(current_users * 0.24)
        cpu = min(98.0, max(15.0, (rps / 250) * 70.0 + random.uniform(-4, 4)))

        points.append({
            "timestamp": t.isoformat(),
            "active_users": int(current_users),
            "requests_per_second": rps,
            "cpu_usage": round(cpu, 1),
            "memory_usage": round(cpu * 0.85 + 15, 1)
        })

    return {
        "generated_points": len(points),
        "data": points
    }

class TrainRequest(BaseModel):
    algorithm: str = "Random Forest Regressor"


@app.post("/api/train")
def train_model(req: TrainRequest):
    """Train on the checked-in synthetic sample dataset and return measured holdout metrics."""
    if req.algorithm != "Random Forest Regressor":
        raise HTTPException(
            status_code=400,
            detail="Only Random Forest Regressor is implemented by the Python API training pipeline."
        )
    if not SAMPLE_DATASET_PATH.is_file():
        raise HTTPException(status_code=503, detail="The bundled sample workload dataset is unavailable.")

    try:
        artifact = train_predictive_model(
            str(SAMPLE_DATASET_PATH),
            model_save_path=str(MODEL_ARTIFACT_PATH),
            split_ratio=0.8,
        )
    except (ValueError, OSError) as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=500, detail="Model training failed. Check backend logs for details.") from exc

    metrics = artifact["metrics"]
    return {
        "algorithm": "Random Forest Regressor",
        "status": "ready",
        "trained_at": artifact["trained_at"],
        "source_dataset": "datasets/sample_workload.csv",
        "source_data_type": "synthetic sample workload; not production telemetry",
        "dataset_rows": artifact["dataset_rows"],
        "train_samples": artifact["train_samples"],
        "test_samples": artifact["test_samples"],
        "metrics": {
            "mae": metrics["mae"],
            "rmse": metrics["rmse"],
            "mape": metrics["mape"],
            "r2": metrics["r2"],
        },
        "feature_importance": artifact["feature_importance"],
        "note": "Metrics are calculated on the chronological holdout portion of the bundled synthetic dataset. They are not production performance claims."
    }


@app.get("/api/predict")
def get_prediction(
    history_rps: List[float] = Query(..., min_length=15, description="At least 15 observed RPS values in chronological order; repeat the query parameter."),
    current_hour: int = Query(14, ge=0, le=23),
    current_day: int = Query(2, ge=0, le=6),
):
    """Generate recursive forecasts from supplied observed history using the trained model."""
    if any(value < 0 for value in history_rps):
        raise HTTPException(status_code=422, detail="RPS observations must be non-negative.")
    if not MODEL_ARTIFACT_PATH.is_file():
        raise HTTPException(status_code=409, detail="No trained model is available. Call POST /api/train first.")
    try:
        predictor = WorkloadPredictor(str(MODEL_ARTIFACT_PATH))
        return predictor.predict_next(history_rps, current_hour=current_hour, current_day=current_day)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except RuntimeError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc



class ScaleDecisionRequest(BaseModel):
    current_instances: int
    predicted_rps: float
    current_cpu: float

@app.post("/api/scale")
def calculate_scaling_action(req: ScaleDecisionRequest):
    """Calculates scaling action based on predictive formula: N = ceil(Predicted_Load / (Capacity * Target_CPU))."""
    cap = current_policy["instance_capacity_rps"]
    target_cpu = current_policy["target_cpu"] / 100.0
    effective_cap = cap * target_cpu

    recommended = max(current_policy["min_instances"], min(current_policy["max_instances"], math.ceil(req.predicted_rps / effective_cap)))
    
    if recommended > req.current_instances:
        action = "SCALE_UP"
        explanation = f"Forecasted RPS ({req.predicted_rps}) exceeds fleet capacity. Adding {recommended - req.current_instances} instances."
    elif recommended < req.current_instances and req.current_cpu < current_policy["scale_down_cpu"]:
        action = "SCALE_DOWN"
        explanation = f"Low forecasted load and CPU ({req.current_cpu}%). Terminating {req.current_instances - recommended} idle instances."
    else:
        action = "MAINTAIN"
        explanation = f"Current fleet size ({req.current_instances}) is optimally balanced."

    return {
        "action": action,
        "current_instances": req.current_instances,
        "recommended_instances": recommended,
        "explanation": explanation,
        "estimated_hourly_cost": round(recommended * current_policy["cost_per_instance_hour"], 2)
    }

